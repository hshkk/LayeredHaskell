-- Testcases

-- An input to be used as a testcase.
-- (descriptor, text to parse, expected result (Show))
type Source = (String, String, String)

-- A testcase.
data Case = Case
  { caseName   :: String               -- ^ The name of the testcase.
  , caseFeats  :: [FeatureName]        -- ^ The feature combination corresponding to the testcase.
  , caseInputs :: [Source]             -- ^ A set of testcase inputs.
  }

-- A set of testcases.
cases :: [Case]
cases =
    -- This should cover every possible feature, at least as generated by "cabal run LayeredHaskell-make -- info".
    -- The structure isn't the most ideal, since the current set of test cases don't catch parse errors.
    -- We could also potentially use the dependency solver to (partially) automatically resolve the list of testcases, 
    -- but I don't think this is necessary right now.
    [ Case "parser (B)"   ["B"]           (concat [e, b])
    , Case "parser (D)"   ["D"]           (concat [e, d])
    , Case "parser (BD)"  ["B", "D"]      (concat [e, b, d])
    , Case "parser (FB)"  ["F", "B"]      (concat [e, b, f, fb])
    , Case "parser (FD)"  ["F", "D"]      (concat [e, d, f, fd])
    , Case "parser (FBD)" ["F", "B", "D"] (concat [e, b, d, f, fb, fd]) 
    , Case "parser (P)"   ["P"]           (concat [e, d, p])
    , Case "parser (PF)"  ["P", "F"]      (concat [e, d, p, f, fd, fp])
    , Case "parser (PB)"  ["P", "B"]      (concat [e, b, d, p])
    , Case "parser (L)"   ["L"]           (concat [e, d, f, l, fd])
    , Case "parser (PL)"  ["P", "L"]      (concat [e, d, p, f, l, fd, fp])
    , Case "parser (LB)"  ["L", "B"]      (concat [e, b, d, f, l, fb, fd])
    , Case "parser (PLB)" ["P", "L", "B"] (concat [e, b, d, p, f, l, fb, fd, fp])
    , Case "parser (PFB)" ["P", "F", "B"] (concat [e, b, d, p, f, fb, fd, fp])
    ]

-- Constructs a testcase input.
-- This should be used over a plain tuple.
source :: String -> String -> String -> Source
source desc src expected = (desc, src, wrap expected)
    where
        -- The Show instance for programs wraps "fromList [...]" around the declarations.
        wrap s = "fromList [" ++ s ++ "]" 

